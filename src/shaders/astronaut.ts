// Shader da OrbitSection: um astronauta em gravidade zero, raymarched.
//
// Tudo é função de distância (SDF) — sem malha, sem textura, sem lib 3D,
// como o núcleo da CoreSection. O corpo é uma união suave de cápsulas e
// caixas arredondadas; o capacete tem um visor que reflete o mesmo céu do
// fundo (estrelas, nebulosa e o planeta com atmosfera). Três fragmentos
// orbitam o astronauta.
//
// Uniforms:
//   uRes    resolução do canvas
//   uTime   tempo (s) — congelado quando prefers-reduced-motion
//   uRot    giro acumulado pelo arraste (yaw, pitch)
//   uMouse  posição do cursor (-1..1), para um leve parallax da câmera
//   uScroll progresso da seção pela tela (0..1): o astronauta deriva

export function buildAstronautSrc(steps: number): string {
  return [
    "precision highp float;",
    "uniform vec2 uRes; uniform float uTime; uniform vec2 uRot; uniform vec2 uMouse; uniform float uScroll;",
    "const vec3 BLUE = vec3(0.114,0.580,0.890);",
    "const vec3 WARM = vec3(0.843,0.643,0.353);",
    "vec3 aPos; mat3 aRot; float gMat; float S;", // S: escala do astronauta no mundo (menor em tela estreita)
    "vec3 sunDir(){ return normalize(vec3(-0.55,0.55,0.62)); }",
    "mat3 rotY(float a){ float s=sin(a),c=cos(a); return mat3(c,0.,-s, 0.,1.,0., s,0.,c); }",
    "mat3 rotX(float a){ float s=sin(a),c=cos(a); return mat3(1.,0.,0., 0.,c,-s, 0.,s,c); }",
    "mat3 rotZ(float a){ float s=sin(a),c=cos(a); return mat3(c,-s,0., s,c,0., 0.,0.,1.); }",
    "float hash1(vec2 p){ return fract(sin(dot(p, vec2(127.1,311.7)))*43758.5453); }",
    "float hash3(vec3 p){ return fract(sin(dot(p, vec3(127.1,311.7,74.7)))*43758.5453); }",
    "float noise(vec3 p){",
    "  vec3 i = floor(p); vec3 f = fract(p); f = f*f*(3.0-2.0*f);",
    "  float a = mix(hash3(i), hash3(i+vec3(1.0,0.0,0.0)), f.x);",
    "  float b = mix(hash3(i+vec3(0.0,1.0,0.0)), hash3(i+vec3(1.0,1.0,0.0)), f.x);",
    "  float c = mix(hash3(i+vec3(0.0,0.0,1.0)), hash3(i+vec3(1.0,0.0,1.0)), f.x);",
    "  float d = mix(hash3(i+vec3(0.0,1.0,1.0)), hash3(i+vec3(1.0,1.0,1.0)), f.x);",
    "  return mix(mix(a,b,f.y), mix(c,d,f.y), f.z);",
    "}",
    "float fbm(vec3 p){ float a = 0.5, s = 0.0; for (int i = 0; i < 4; i++) { s += a*noise(p); p *= 2.03; a *= 0.5; } return s; }",
    "float smin(float a, float b, float k){ float h = clamp(0.5+0.5*(b-a)/k, 0.0, 1.0); return mix(b,a,h) - k*h*(1.0-h); }",
    "float sdCap(vec3 p, vec3 a, vec3 b, float r){ vec3 pa = p-a, ba = b-a; float h = clamp(dot(pa,ba)/dot(ba,ba), 0.0, 1.0); return length(pa-ba*h) - r; }",
    "float sdRBox(vec3 p, vec3 b, float r){ vec3 q = abs(p)-b+r; return length(max(q,0.0)) + min(max(q.x,max(q.y,q.z)),0.0) - r; }",
    "float sdTorus(vec3 p, vec2 t){ vec2 q = vec2(length(p.xz)-t.x, p.y); return length(q)-t.y; }",

    // corpo (espaço local, astronauta de frente para +z): tronco, gola,
    // braços (o direito acenando), pernas soltas e botas
    "float body(vec3 p){",
    "  float s1 = sin(uTime*0.9)*0.08, s2 = sin(uTime*0.7+1.3)*0.10;",
    "  float d = sdRBox(p-vec3(0.0,0.18,0.0), vec3(0.34,0.40,0.24), 0.16);",
    "  d = smin(d, sdTorus(p-vec3(0.0,0.62,0.0), vec2(0.22,0.06)), 0.05);",
    "  vec3 shL = vec3(0.40,0.46,0.0), shR = vec3(-0.40,0.46,0.0);",
    "  vec3 elL = vec3(0.66,0.16+s1,0.14), elR = vec3(-0.66,0.30-s2,-0.06);",
    "  vec3 hL = vec3(0.62,-0.16+s1*1.6,0.38), hR = vec3(-0.80,0.66-s2*1.4,0.16);",
    "  d = smin(d, sdCap(p,shL,elL,0.12), 0.08); d = smin(d, sdCap(p,elL,hL,0.105), 0.05);",
    "  d = smin(d, sdCap(p,shR,elR,0.12), 0.08); d = smin(d, sdCap(p,elR,hR,0.105), 0.05);",
    "  d = smin(d, length(p-hL)-0.125, 0.04); d = smin(d, length(p-hR)-0.125, 0.04);",
    "  vec3 hpL = vec3(0.17,-0.18,0.0), hpR = vec3(-0.17,-0.18,0.0);",
    "  vec3 knL = vec3(0.24,-0.62,0.18+s2*0.5), knR = vec3(-0.22,-0.58,-0.10-s1);",
    "  vec3 ftL = vec3(0.26,-1.02,0.02+s2*0.5), ftR = vec3(-0.30,-0.98,-0.36-s1);",
    "  d = smin(d, sdCap(p,hpL,knL,0.15), 0.08); d = smin(d, sdCap(p,knL,ftL,0.135), 0.05);",
    "  d = smin(d, sdCap(p,hpR,knR,0.15), 0.08); d = smin(d, sdCap(p,knR,ftR,0.135), 0.05);",
    "  d = smin(d, sdRBox(p-ftL-vec3(0.0,-0.05,0.06), vec3(0.11,0.08,0.17), 0.06), 0.04);",
    "  d = smin(d, sdRBox(p-ftR-vec3(0.0,-0.05,0.06), vec3(0.11,0.08,0.17), 0.06), 0.04);",
    "  return d;",
    "}",

    // cena inteira no espaço do mundo; gMat: 0 traje, 1 mochila, 2 capacete, 3 fragmento
    "float map(vec3 pw){",
    "  vec3 p = aRot*(pw-aPos)/S;",
    "  float b = body(p);",
    "  float k = sdRBox(p-vec3(0.0,0.22,-0.38), vec3(0.30,0.40,0.14), 0.08);",
    "  float h = length(p-vec3(0.0,0.97,0.02)) - 0.40;",
    "  float dbr = 1e5;",
    "  for (int i = 0; i < 3; i++) {",
    "    float fi = float(i); float a = uTime*(0.35+0.12*fi) + fi*2.1;",
    "    vec3 c = vec3(cos(a)*1.3, sin(a*0.7+fi)*0.7+0.15, sin(a)*0.75);",
    "    vec3 q = rotX(uTime*0.8+fi) * rotY(uTime*0.6+fi*1.3) * (p-c);",
    "    dbr = min(dbr, sdRBox(q, vec3(0.07+0.025*fi), 0.018));",
    "  }",
    "  float d = min(min(b,k), min(h,dbr));",
    "  gMat = d == h ? 2.0 : (d == k ? 1.0 : (d == dbr ? 3.0 : 0.0));",
    "  return d*S;",
    "}",
    "vec3 calcNormal(vec3 p){",
    "  vec2 e = vec2(1.0,-1.0)*0.0012;",
    "  return normalize(e.xyy*map(p+e.xyy) + e.yyx*map(p+e.yyx) + e.yxy*map(p+e.yxy) + e.xxx*map(p+e.xxx));",
    "}",
    "float softShadow(vec3 ro, vec3 rd){",
    "  float res = 1.0, t = 0.02;",
    "  for (int i = 0; i < 18; i++) { float h = map(ro+rd*t); res = min(res, 10.0*h/t); t += clamp(h, 0.02, 0.2); if (res < 0.02 || t > 1.6) break; }",
    "  return clamp(res, 0.0, 1.0);",
    "}",
    "float calcAO(vec3 p, vec3 n){",
    "  float o = 0.0, s = 1.0;",
    "  for (int i = 0; i < 4; i++) { float h = 0.015+0.05*float(i); o += (h-map(p+n*h))*s; s *= 0.7; }",
    "  return clamp(1.0-2.4*o, 0.0, 1.0);",
    "}",

    // céu: gradiente, nebulosa, estrelas, brilho do sol e o planeta com atmosfera.
    // Usado no fundo E no reflexo do visor.
    "vec3 sky(vec3 ro, vec3 rd){",
    "  vec3 col = mix(vec3(0.006,0.007,0.012), vec3(0.016,0.026,0.05), smoothstep(-0.4,0.6,rd.y));",
    "  col += BLUE*pow(fbm(rd*2.2+vec3(0.0,0.0,uTime*0.01)), 3.0)*0.38;",
    "  col += WARM*pow(fbm(rd*3.1+7.3), 4.0)*0.2;",
    "  vec2 sp = vec2(atan(rd.z, rd.x), asin(clamp(rd.y,-1.0,1.0)))*90.0;",
    "  float hs = hash1(floor(sp));",
    "  float star = step(0.975,hs) * smoothstep(0.14,0.0,length(fract(sp)-0.5)) * (0.55+0.45*sin(uTime*2.0+hs*40.0));",
    "  col += vec3(0.9,0.92,1.0)*star*1.3;",
    "  float sd = max(dot(rd, sunDir()), 0.0);",
    "  col += WARM*pow(sd,40.0)*0.6 + vec3(1.0,0.95,0.85)*pow(sd,900.0)*3.0;",
    "  vec3 pc = vec3(-1.8,-7.2,-7.0); float pr = 6.2;",
    "  vec3 oc = ro-pc; float b = dot(oc,rd); float c = dot(oc,oc)-pr*pr; float h = b*b-c;",
    "  if (b < 0.0) {",
    "    float closest = sqrt(max(dot(oc,oc)-b*b, 0.0));",
    "    float atm = smoothstep(pr+1.1, pr, closest);",
    "    col += BLUE*atm*atm*0.9;",
    "  }",
    "  if (h > 0.0 && b < 0.0) {",
    "    vec3 pp = ro + rd*(-b-sqrt(h)); vec3 pn = normalize(pp-pc);",
    "    float pd = max(dot(pn, sunDir()), 0.0);",
    "    float bands = fbm(pn*vec3(3.0,9.0,3.0)+3.0);",
    "    vec3 surf = mix(vec3(0.02,0.04,0.08), vec3(0.09,0.15,0.24), bands) * (0.12+pd*1.1);",
    "    float rim = pow(1.0-max(dot(pn,-rd),0.0), 2.5);",
    "    col = surf + BLUE*rim*0.95 + WARM*pow(pd,6.0)*0.06;",
    "  }",
    "  return col;",
    "}",

    "void main(){",
    "  vec2 uv = (gl_FragCoord.xy - 0.5*uRes) / uRes.y;",
    // telas largas: astronauta à direita (o texto fica à esquerda); estreitas: centro
    "  float wide = smoothstep(0.9, 1.5, uRes.x/uRes.y);",
    "  S = mix(0.44, 0.6, wide);",
    // em tela estreita o texto ocupa a metade de baixo: o astronauta sobe
    "  aPos = vec3(mix(0.0, 1.0, wide) - uScroll*0.3*wide, 0.14 + (1.0-wide)*0.26 + sin(uTime*0.6)*0.07 - (uScroll-0.5)*0.3, 0.0);",
    "  aRot = rotZ(sin(uTime*0.23)*0.18) * rotX(uRot.y + sin(uTime*0.31)*0.12) * rotY(uRot.x + uTime*0.1);",
    "  vec3 ro = vec3(uMouse.x*0.18, uMouse.y*0.12, 4.3);",
    "  vec3 rd = normalize(vec3(uv, -1.55));",
    "  vec3 col = sky(ro, rd);",
    // só marcha dentro da esfera que envolve o astronauta: o resto da tela é só céu
    "  vec3 oc = ro-aPos; float b = dot(oc,rd); float R = 1.62*S; float h = b*b - (dot(oc,oc)-R*R);",
    "  if (h > 0.0) {",
    "    float t1 = -b+sqrt(h); float t = max(-b-sqrt(h), 0.0); bool hit = false;",
    `    for (int i = 0; i < ${steps}; i++) {`,
    "      float d = map(ro+rd*t);",
    "      if (d < 0.0012) { hit = true; break; }",
    "      t += d*0.85; if (t > t1) break;",
    "    }",
    "    if (hit) {",
    "      vec3 p = ro+rd*t; float m = gMat;",
    "      vec3 n = calcNormal(p); float ao = calcAO(p,n);",
    "      vec3 L = sunDir(); vec3 V = -rd; vec3 H = normalize(L+V);",
    "      float dif = max(dot(n,L), 0.0) * softShadow(p+n*0.004, L);",
    "      float fres = pow(1.0-max(dot(n,V),0.0), 3.0);",
    "      float fill = max(dot(n, vec3(0.0,-1.0,0.0)), 0.0);", // luz azul refletida pelo planeta
    "      float spec = pow(max(dot(n,H),0.0), 48.0);",
    "      vec3 q = aRot*(p-aPos)/S;",
    "      if (m < 0.5) {",
    "        float s1 = sin(uTime*0.9)*0.08, s2 = sin(uTime*0.7+1.3)*0.10;",
    "        float glove = max(step(length(q-vec3(0.62,-0.16+s1*1.6,0.38)), 0.17), step(length(q-vec3(-0.80,0.66-s2*1.4,0.16)), 0.17));",
    "        float boot = step(q.y, -0.9);",
    "        vec3 alb = mix(vec3(0.95,0.94,0.92), vec3(0.32,0.32,0.35), max(glove, boot));",
    "        col = alb*(0.09 + dif*vec3(1.0,0.94,0.84)*1.25)*ao + BLUE*fill*0.28*ao + BLUE*fres*0.45 + spec*0.35;",
    "        float front = step(0.18, q.z);",
    "        float led1 = smoothstep(0.04,0.022,length(q.xy-vec2(0.13,0.30)))*front;",
    "        float led2 = smoothstep(0.04,0.022,length(q.xy-vec2(0.02,0.30)))*front;",
    "        col += BLUE*led1*(1.4+0.8*sin(uTime*3.0)) + WARM*led2*1.6;",
    "      } else if (m < 1.5) {",
    "        col = vec3(0.5,0.5,0.53)*(0.05+dif*0.9)*ao + BLUE*fres*0.4 + spec*0.15;",
    "      } else if (m < 2.5) {",
    "        vec3 nl = normalize(q-vec3(0.0,0.97,0.02));",
    "        float visor = smoothstep(0.26,0.36,nl.z) * smoothstep(0.62,0.5,abs(nl.y-0.04));",
    "        vec3 shell = vec3(0.86)*(0.06+dif)*ao + BLUE*fres*0.5 + spec*0.3;",
    "        vec3 r = reflect(rd,n);",
    "        vec3 gold = vec3(1.0,0.74,0.38);",
    "        vec3 glass = vec3(0.10,0.065,0.03)*(0.35+0.65*max(dot(n,L),0.0))",
    "                   + sky(p,r)*gold*(0.7+0.5*fres)*2.4",
    "                   + gold*smoothstep(0.1,-0.5,r.y)*0.30 + BLUE*smoothstep(-0.15,-0.6,r.y)*0.45",
    "                   + pow(max(dot(r,L),0.0),120.0)*vec3(1.0,0.92,0.75)*3.0;",
    "        col = mix(shell, glass, visor);",
    "      } else {",
    "        col = vec3(0.22,0.23,0.26)*(0.05+dif)*ao + BLUE*fres*1.1 + spec*0.4;",
    "      }",
    "    }",
    "  }",
    "  col = col/(1.0+col*0.55);",
    "  col = pow(col, vec3(0.88));",
    "  col *= 0.5 + 0.5*smoothstep(1.35, 0.25, length(uv*vec2(0.85,1.1)));",
    "  col += (hash1(gl_FragCoord.xy + fract(uTime)*91.0) - 0.5)*0.014;",
    "  gl_FragColor = vec4(col, 1.0);",
    "}",
  ].join("\n");
}

export const VERTEX_SRC = "attribute vec2 aP; void main(){ gl_Position = vec4(aP,0.0,1.0); }";
