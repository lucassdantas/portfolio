    "    camD = mix(4.4, 1.45, close); camA = 0.18*sin(lp*3.0); camH = mix(0.25, 0.1, lp);",
    "    target = vec3(0.0);",
    "  } else {",
    "    lp = (p-0.72)/0.28;",
    "    mat = smoothstep(0.02, 0.18, lp);",
    "    gJet = smoothstep(0.05, 0.2, lp);",
    "    aPos = mix(vec3(-1.6,-0.5,-0.4), vec3(2.6,1.7,-4.6), smoothstep(0.08,1.0,lp));",
