    "  if (m < 0.5) { vec2 wv3 = sin(uv*260.0); col += sun * pow(1.0-NoV, 3.0) * 0.2 * (0.3+0.7*dif) * alb * (0.8 + 0.4*abs(wv3.x*wv3.y)); }",
