    "    float vf = 0.03 + 0.97*pow(1.0-NoV, 5.0);",
    "    vec3 glass = vec3(0.003,0.004,0.006) + skyLite(p3,r)*vf*1.5 + pow(max(dot(r,L1),0.0),500.0)*vec3(1.0)*7.0 + pow(max(dot(r,L1),0.0),30.0)*0.1;",
