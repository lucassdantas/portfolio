// Shader da OrbitSection: astronauta raymarched guiado pela rolagem.
//
// Tudo é função de distância (SDF) — sem malha, sem textura em arquivo, sem
// lib 3D, como o núcleo da CoreSection. A "textura" do traje (trama do
// tecido, costuras) é procedural: ruído perturbando a normal + linhas.
//
// `uProg` (0..1) é o progresso da rolagem pela seção e conduz a coreografia:
//   0.00–0.28  materializa a partir de poeira azul; o céu entra aos poucos
//              por cima das partículas do site, sem corte
//   0.04–0.44  câmera se aproxima; ele gira para encarar a câmera
//   0.30–0.62  aceno
//   0.45–0.74  close no capacete — o visor reflete o planeta
//   0.66–1.00  liga os jatos e vai embora; o céu some e devolve as partículas
//
// Uniforms: uRes, uTime (congelado com reduced-motion), uProg, uRot (arraste),
// uMouse (parallax leve da câmera).

export function buildAstronautSrc(steps: number): string {
  return [
    "precision highp float;",
    "uniform vec2 uRes; uniform float uTime; uniform float uProg; uniform vec2 uRot; uniform vec2 uMouse;",
    "const vec3 BLUE = vec3(0.114,0.580,0.890);",
    "const vec3 CYAN = vec3(0.40,0.85,1.0);",
    "const vec3 NAVY = vec3(0.06,0.10,0.20);",
    "const float S = 0.62;",
    // estado da cena, calculado uma vez em main e lido por map()
    "vec3 aPos; mat3 aRot; float gMat; float gJet;",
    "vec3 jEL, jER, jHL, jHR, jKL, jKR, jFL, jFR;",
    "const vec3 SHL = vec3(0.43,0.50,0.0); const vec3 SHR = vec3(-0.43,0.50,0.0);",
    "const vec3 HPL = vec3(0.17,-0.22,0.0); const vec3 HPR = vec3(-0.17,-0.22,0.0);",

    "mat3 rotY(float a){ float s=sin(a),c=cos(a); return mat3(c,0.,-s, 0.,1.,0., s,0.,c); }",
    "mat3 rotX(float a){ float s=sin(a),c=cos(a); return mat3(1.,0.,0., 0.,c,-s, 0.,s,c); }",
    "mat3 rotZ(float a){ float s=sin(a),c=cos(a); return mat3(c,-s,0., s,c,0., 0.,0.,1.); }",
    "float hash1(vec2 p){ return fract(sin(dot(p, vec2(127.1,311.7)))*43758.5453); }",
    "float hash3(vec3 p){ return fract(sin(dot(p, vec3(127.1,311.7,74.7)))*43758.5453); }",
    "float noise(vec3 p){",
    "  vec3 i = floor(p); vec3 f = fract(p); f = f*f*(3.0-2.0*f);",
    "  float a = mix(hash3(i), hash3(i+vec3(1.0,0.0,0.0)), f.x);",
    "  float b = mix(hash3(i+vec3(0.0,1.0,0.0)), hash3(i+vec3(1.0,1.0,0.0)), f.x);",
    "  float c = mix(hash3(i+vec3(0.0,0.0,1.0)), hash3(i+vec3(1.0,0.0,1.0)), f.x);",
    "  float d = mix(hash3(i+vec3(0.0,1.0,1.0)), hash3(i+vec3(1.0,1.0,1.0)), f.x);",
    "  return mix(mix(a,b,f.y), mix(c,d,f.y), f.z);",
    "}",
    "float fbm(vec3 p){ float a = 0.5, s = 0.0; for (int i = 0; i < 4; i++) { s += a*noise(p); p = p*2.03 + 1.7; a *= 0.5; } return s; }",
    "float smin(float a, float b, float k){ float h = clamp(0.5+0.5*(b-a)/k, 0.0, 1.0); return mix(b,a,h) - k*h*(1.0-h); }",
    "float sdCap(vec3 p, vec3 a, vec3 b, float r){ vec3 pa = p-a, ba = b-a; float h = clamp(dot(pa,ba)/dot(ba,ba), 0.0, 1.0); return length(pa-ba*h) - r; }",
    "float sdRBox(vec3 p, vec3 b, float r){ vec3 q = abs(p)-b+r; return length(max(q,0.0)) + min(max(q.x,max(q.y,q.z)),0.0) - r; }",
    "float sdTorus(vec3 p, vec2 t){ vec2 q = vec2(length(p.xz)-t.x, p.y); return length(q)-t.y; }",
    "float sdEll(vec3 p, vec3 r){ float k0 = length(p/r); float k1 = length(p/(r*r)); return k0*(k0-1.0)/k1; }",

    // pose: membros soltos de gravidade zero + aceno controlado pela rolagem
    "void pose(float wave){",
    "  float s1 = sin(uTime*0.9)*0.07, s2 = sin(uTime*0.7+1.3)*0.09;",
    "  float wv = sin(uTime*7.0)*0.16*wave;",
    "  jEL = vec3(0.70,0.16+s1,0.12); jHL = vec3(0.64,-0.18+s1*1.5,0.40);",
    "  jER = mix(vec3(-0.70,0.22-s2,-0.04), vec3(-0.78,0.62,0.05), wave);",
    "  jHR = mix(vec3(-0.66,-0.12-s2*1.4,0.30), vec3(-0.70+wv,1.12,0.18), wave);",
    "  jKL = vec3(0.24,-0.66,0.18+s2*0.5); jFL = vec3(0.27,-1.08,0.02+s2*0.5);",
    "  jKR = vec3(-0.22,-0.62,-0.10-s1); jFR = vec3(-0.30,-1.04,-0.36-s1);",
    "}",

    // gMat: 0 tecido, 1 luva/bota, 2 anéis azuis, 3 mochila, 4 capacete
    "float map(vec3 pw){",
    "  vec3 p = aRot*(pw-aPos)/S;",
    "  float torso = sdRBox(p-vec3(0.0,0.15,0.0), vec3(0.37,0.43,0.27), 0.21);",
    "  torso = smin(torso, sdRBox(p-vec3(0.0,0.20,0.27), vec3(0.17,0.11,0.06), 0.03), 0.03);",
    "  float arms = min(sdCap(p,SHL,jEL,0.14), sdCap(p,SHR,jER,0.14));",
    "  arms = min(arms, min(sdCap(p,jEL,jHL,0.125), sdCap(p,jER,jHR,0.125)));",
    "  float legs = min(sdCap(p,HPL,jKL,0.17), sdCap(p,HPR,jKR,0.17));",
    "  legs = min(legs, min(sdCap(p,jKL,jFL,0.155), sdCap(p,jKR,jFR,0.155)));",
    "  float suit = smin(smin(torso, arms, 0.1), legs, 0.1);",
    "  float gb = min(length(p-jHL)-0.14, length(p-jHR)-0.14);",
    "  gb = min(gb, sdRBox(p-jFL-vec3(0.0,-0.06,0.06), vec3(0.13,0.09,0.2), 0.07));",
    "  gb = min(gb, sdRBox(p-jFR-vec3(0.0,-0.06,0.06), vec3(0.13,0.09,0.2), 0.07));",
    "  float rings = sdTorus(p-vec3(0.0,0.64,0.0), vec2(0.25,0.06));",
    "  rings = min(rings, sdCap(p, mix(jEL,jHL,0.80), mix(jEL,jHL,0.88), 0.138));",
    "  rings = min(rings, sdCap(p, mix(jER,jHR,0.80), mix(jER,jHR,0.88), 0.138));",
    "  rings = min(rings, sdCap(p, mix(jKL,jFL,0.84), mix(jKL,jFL,0.92), 0.168));",
    "  rings = min(rings, sdCap(p, mix(jKR,jFR,0.84), mix(jKR,jFR,0.92), 0.168));",
    "  float pack = sdRBox(p-vec3(0.0,0.20,-0.41), vec3(0.33,0.43,0.16), 0.09);",
    "  float helm = sdEll(p-vec3(0.0,1.0,0.03), vec3(0.43,0.42,0.43));",
    "  float d = min(min(min(suit,gb),rings), min(pack,helm));",
    "  gMat = d == suit ? 0.0 : (d == gb ? 1.0 : (d == rings ? 2.0 : (d == pack ? 3.0 : 4.0)));",
    "  return d*S;",
    "}",
    "vec3 calcNormal(vec3 p){",
    "  vec2 e = vec2(1.0,-1.0)*0.0009;",
    "  return normalize(e.xyy*map(p+e.xyy) + e.yyx*map(p+e.yyx) + e.yxy*map(p+e.yxy) + e.xxx*map(p+e.xxx));",
    "}",
    "float softShadow(vec3 ro, vec3 rd){",
    "  float res = 1.0, t = 0.02;",
    "  for (int i = 0; i < 16; i++) { float h = map(ro+rd*t); res = min(res, 8.0*h/t); t += clamp(h, 0.02, 0.2); if (res < 0.02 || t > 1.8) break; }",
    "  return clamp(res, 0.0, 1.0);",
    "}",
    "float calcAO(vec3 p, vec3 n){",
    "  float o = 0.0, s = 1.0;",
    "  for (int i = 0; i < 5; i++) { float h = 0.01+0.045*float(i); o += (h-map(p+n*h))*s; s *= 0.75; }",
    "  return clamp(1.0-2.6*o, 0.0, 1.0);",
    "}",

    // céu azul: gradiente, nebulosa, estrelas, planeta-oceano com nuvens e atmosfera
    "vec3 sky(vec3 ro, vec3 rd){",
    "  vec3 col = mix(vec3(0.004,0.009,0.026), vec3(0.02,0.06,0.15), smoothstep(-0.7,0.8,rd.y));",
    "  col += BLUE*pow(fbm(rd*1.7+vec3(0.0,0.0,uTime*0.006)), 2.4)*0.7;",
    "  col += CYAN*pow(fbm(rd*3.3+5.0), 4.0)*0.35;",
    "  vec2 sp = vec2(atan(rd.z, rd.x), asin(clamp(rd.y,-1.0,1.0)));",
    "  vec2 g1 = sp*110.0; float h1 = hash1(floor(g1));",
    "  col += vec3(0.8,0.9,1.0) * step(0.972,h1) * smoothstep(0.16,0.0,length(fract(g1)-0.5)) * (0.5+0.5*sin(uTime*1.7+h1*50.0)) * 1.4;",
    "  vec2 g2 = sp*36.0; float h2 = hash1(floor(g2)+7.0);",
    "  col += CYAN * step(0.985,h2) * smoothstep(0.22,0.0,length(fract(g2)-0.5)) * 1.6;",
    "  vec3 pc = vec3(0.0,-9.5,-5.0); float pr = 8.0;",
    "  vec3 oc = ro-pc; float b = dot(oc,rd); float c = dot(oc,oc)-pr*pr; float h = b*b-c;",
    "  if (b < 0.0) {",
    "    float closest = sqrt(max(dot(oc,oc)-b*b, 0.0));",
    "    float atm = smoothstep(pr+1.4, pr, closest);",
    "    col += CYAN*atm*atm*0.55 + BLUE*atm*0.6;",
    "  }",
    "  if (h > 0.0 && b < 0.0) {",
    "    vec3 pp = ro + rd*(-b-sqrt(h)); vec3 pn = normalize(pp-pc);",
    "    vec3 L = normalize(vec3(0.6,0.7,0.5));",
    "    float pd = max(dot(pn,L)*0.8+0.2, 0.0);",
    "    float land = fbm(pn*4.5);",
    "    vec3 ocean = mix(vec3(0.01,0.05,0.16), vec3(0.04,0.22,0.52), land);",
    "    float clouds = smoothstep(0.52,0.72, fbm(pn*7.0+vec3(uTime*0.01,0.0,0.0)));",
    "    vec3 surf = mix(ocean, vec3(0.85,0.92,1.0), clouds*0.75) * (0.08+pd*1.1);",
    "    float rim = pow(1.0-max(dot(pn,-rd),0.0), 2.2);",
    "    col = surf + CYAN*rim*0.9 + BLUE*rim*0.5;",
    "  }",
    "  return col;",
    "}",

    // poeira: pontos piscando em espaço de tela, usados na materialização
    "float dust(vec2 uv){",
    "  vec2 g = uv*140.0; float h = hash1(floor(g));",
    "  float tw = 0.5+0.5*sin(uTime*4.0 + h*60.0);",
    "  return step(0.9, h) * smoothstep(0.28, 0.0, length(fract(g)-0.5)) * tw;",
    "}",

    "void main(){",
    "  vec2 uv = (gl_FragCoord.xy - 0.5*uRes) / uRes.y;",
    "  float p = uProg;",
    "  float mat = smoothstep(0.02, 0.28, p);",
    "  float wave = smoothstep(0.30,0.40,p) * (1.0-smoothstep(0.55,0.64,p));",
    "  float close = smoothstep(0.45,0.58,p) * (1.0-smoothstep(0.64,0.74,p));",
    "  float fly = smoothstep(0.74, 1.0, p);",
    "  gJet = smoothstep(0.66, 0.76, p);",
    "  pose(wave);",
    "  float wide = smoothstep(0.9, 1.5, uRes.x/uRes.y);",
    "  aPos = vec3(0.0, sin(uTime*0.6)*0.05, 0.0) + vec3(1.9, 1.5, -4.0)*fly*fly;",
    "  float yaw = mix(2.4, 0.15, smoothstep(0.04,0.44,p)) - 1.1*smoothstep(0.66,0.86,p) + uRot.x + sin(uTime*0.21)*0.07;",
    "  float pitch = uRot.y + sin(uTime*0.31)*0.07 - 0.35*fly;",
    "  aRot = rotZ(sin(uTime*0.23)*0.12 + 0.5*fly) * rotX(pitch) * rotY(yaw);",
    // câmera em trilho: longe → perto → close no visor → recua
    "  float camD = mix(8.0, 3.5, smoothstep(0.0,0.45,p));",
    "  camD = mix(camD, 1.55, close);",
    "  camD = mix(camD, 6.0, smoothstep(0.74,1.0,p));",
    "  float camA = mix(-0.55, 0.2, smoothstep(0.0,0.6,p)) - 0.7*smoothstep(0.62,1.0,p) + uMouse.x*0.08;",
    "  float camH = mix(0.9, 0.08, smoothstep(0.0,0.5,p)) + 0.25*close + uMouse.y*0.06;",
    "  vec3 helmW = aPos + S*vec3(0.0,1.0,0.0);",
    // tela larga: a câmera mira à esquerda do astronauta, que fica à direita do texto
    "  vec3 target = mix(vec3(-0.75*wide, 0.12, 0.0), helmW, close);",
    "  target = mix(target, aPos*0.5, fly);",
    "  vec3 ro = target + vec3(sin(camA)*camD, camH, cos(camA)*camD);",
    "  vec3 fw = normalize(target-ro); vec3 rt = normalize(cross(fw, vec3(0.0,1.0,0.0))); vec3 up = cross(rt, fw);",
    "  vec3 rd = normalize(fw*1.6 + rt*uv.x + up*uv.y);",

    // o céu entra e sai aos poucos: no começo e no fim, as partículas do site aparecem por trás
    "  float bgA = smoothstep(0.02,0.22,p) * (1.0-smoothstep(0.86,0.99,p));",
    "  vec3 col = sky(ro, rd)*bgA; float alpha = bgA;",

    "  vec3 oc = ro-aPos-S*vec3(0.0,0.1,0.0); float b = dot(oc,rd); float R = 2.7*S; float h = b*b - (dot(oc,oc)-R*R);",
    "  if (h > 0.0) {",
    "    float t1 = -b+sqrt(h); float t = max(-b-sqrt(h), 0.0); bool hit = false;",
    "    float dmin = 1e3; float jet = 0.0;",
    `    for (int i = 0; i < ${steps}; i++) {`,
    "      vec3 pw = ro+rd*t; float d = map(pw); dmin = min(dmin, d);",
    "      if (gJet > 0.0) {",
    "        vec3 q = aRot*(pw-aPos)/S;",
    "        float dj = min(sdCap(q, vec3(0.14,-0.22,-0.56), vec3(0.24,-1.9,-1.3), 0.0), sdCap(q, vec3(-0.14,-0.22,-0.56), vec3(-0.24,-1.9,-1.3), 0.0));",
    "        jet += gJet * 0.11 / (1.0 + dj*dj*160.0);",
    "      }",
    "      if (d < 0.0009) { hit = true; break; }",
    "      t += d*0.8; if (t > t1) break;",
    "    }",
    "    if (hit) {",
    "      vec3 p3 = ro+rd*t; float m = gMat;",
    "      vec3 q = aRot*(p3-aPos)/S;",
    // materialização: o ruído decide o que já 'chegou'; a borda brilha em ciano
    "      float dn = noise(q*5.0+3.0)*0.75 + noise(q*13.0)*0.25;",
    "      float th = mat*1.1;",
    "      if (dn < th) {",
    "        vec3 n = calcNormal(p3);",
    "        if (m < 0.5) n = normalize(n + (vec3(noise(q*34.0), noise(q*34.0+11.0), noise(q*34.0+23.0))-0.5)*0.22);",
    "        float ao = calcAO(p3,n);",
    "        vec3 V = -rd;",
    "        vec3 L1 = normalize(vec3(0.6,0.7,0.5)); vec3 L2 = normalize(vec3(-0.45,0.25,-0.85));",
    "        float sh = softShadow(p3+n*0.003, L1);",
    "        float d1 = clamp((dot(n,L1)+0.25)/1.25, 0.0, 1.0)*sh;",
    "        float d2 = max(dot(n,L2),0.0);",
    "        float fres = pow(1.0-max(dot(n,V),0.0), 3.0);",
    "        float spec = pow(max(dot(n, normalize(L1+V)),0.0), 60.0)*sh;",
    "        vec3 amb = mix(vec3(0.02,0.05,0.12), vec3(0.18,0.30,0.50), n.y*0.5+0.5);",
    "        vec3 alb = vec3(0.93,0.95,0.98);",
    "        float emit = 0.0;",
    "        if (m < 0.5) {",
    // costuras do tecido: anéis finos ao longo do corpo + costura central do tronco
    "          float seam = smoothstep(0.035,0.0, abs(fract(q.y*6.5)-0.5)-0.44) * 0.22;",
    "          seam += smoothstep(0.012,0.0, abs(q.x)) * step(-0.25,q.y) * step(q.y,0.55) * step(0.2,q.z) * 0.25;",
    "          alb *= 1.0 - seam;",
    "          float badge = smoothstep(0.075,0.06, length(q-vec3(0.55,0.36,0.10)));",
    "          alb = mix(alb, BLUE*0.8, badge);",
    "          float front = step(0.31, q.z);",
    "          float led1 = smoothstep(0.032,0.018, length(q.xy-vec2(0.09,0.23))) * front;",
    "          float led2 = smoothstep(0.032,0.018, length(q.xy-vec2(-0.02,0.23))) * front;",
    "          float bar = smoothstep(0.02,0.0, abs(q.y-0.14)) * step(abs(q.x),0.12) * front;",
    "          emit += led1*(1.6+0.8*sin(uTime*3.0)) + bar*1.2 + led2*1.4;",
    "        } else if (m < 1.5) {",
    "          alb = NAVY;",
    "        } else if (m < 2.5) {",
    "          alb = BLUE*0.55; emit += 0.55;",
    "        } else if (m < 3.5) {",
    "          float stripe = smoothstep(0.03,0.0, abs(q.y-0.36));",
    "          alb = mix(vec3(0.88,0.90,0.94), BLUE, stripe); emit += stripe*0.6;",
    "        }",
    "        col = alb*(amb*0.9*ao + d1*vec3(1.0,0.97,0.94)*1.15) + BLUE*d2*0.9*ao + CYAN*fres*0.55 + spec*0.45;",
    "        col += BLUE*emit;",
    "        if (m > 3.5) {",
    "          vec3 nl = normalize(q-vec3(0.0,1.0,0.03));",
    "          float vm = smoothstep(0.24,0.30,nl.z) * smoothstep(0.66,0.58,abs(nl.y-0.02));",
    "          float trim = smoothstep(0.035,0.0, abs(nl.z-0.255)) * smoothstep(0.7,0.55,abs(nl.y-0.02));",
    "          vec3 r = reflect(rd,n);",
    "          vec3 film = 0.5+0.5*cos(6.2832*(fres*1.3 + vec3(0.0,0.18,0.42)));",
    "          vec3 glass = vec3(0.01,0.015,0.03) + sky(p3,r)*mix(vec3(0.7,0.85,1.0), film, 0.45)*(0.55+0.65*fres)*1.9",
    "                     + pow(max(dot(r,L1),0.0),160.0)*vec3(1.0,0.97,0.92)*3.5 + CYAN*fres*0.35;",
    "          col = mix(col, glass, vm) + CYAN*trim*1.6;",
    "        }",
    "        float edge = smoothstep(th-0.09, th, dn);",
    "        col = mix(col, CYAN*2.2, edge);",
    "        alpha = 1.0;",
    "      }",
    "    }",
    // poeira azul em volta do corpo enquanto ele se forma, e o brilho dos jatos
    "    float dz = (1.0-mat) * smoothstep(0.35*S, 0.0, dmin) * dust(uv) * 2.2;",
    "    col += CYAN*dz; alpha = max(alpha, clamp(dz, 0.0, 1.0));",
    "    col += (BLUE*0.8 + CYAN*0.6) * jet; alpha = max(alpha, clamp(jet, 0.0, 1.0));",
    "  }",

    // `col` vem pré-multiplicado por alpha; o tone mapping trabalha na cor real
    "  col = col / max(alpha, 0.001);",
    "  col = col*(2.51*col+0.03)/(col*(2.43*col+0.59)+0.14);", // ACES
    "  col = pow(clamp(col,0.0,1.0), vec3(0.92));",
    "  float vig = 0.55 + 0.45*smoothstep(1.4, 0.2, length(uv*vec2(0.85,1.1)));",
    "  col *= mix(1.0, vig, bgA);",
    "  col += (hash1(gl_FragCoord.xy + fract(uTime)*91.0) - 0.5)*0.012*alpha;",
    "  gl_FragColor = vec4(col*alpha, alpha);",
    "}",
  ].join("\n");
}

export const VERTEX_SRC = "attribute vec2 aP; void main(){ gl_Position = vec4(aP,0.0,1.0); }";
